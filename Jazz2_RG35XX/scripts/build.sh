#!/usr/bin/env bash
set -euo pipefail
source "$(dirname "$0")/env.sh"
mkdir -p "$WORK/logs"
export LD_LIBRARY_PATH="$RG_TOOLCHAIN/lib"
export PKG_CONFIG_LIBDIR="$RG_SYSROOT/usr/lib/pkgconfig" PKG_CONFIG_SYSROOT_DIR="$RG_SYSROOT"
[[ -d "$WORK/engine" ]] || bash "$PORT/scripts/source.sh"
cmake -S "$WORK/engine" -B "$WORK/build" -G Ninja \
    -DCMAKE_TOOLCHAIN_FILE="$PORT/cmake/garlic.cmake" -DCMAKE_BUILD_TYPE=Release \
    -DNCINE_OVERRIDE_CONTENT_PATH=Content/ -DNCINE_PREFERRED_RHI=Software -DNCINE_PREFERRED_BACKEND=SDL2 -DNCINE_RHI_USE_FB16=ON \
    -DNCINE_WITH_AUDIO=ON -DNCINE_WITH_VORBIS=OFF -DNCINE_WITH_OPENMPT=ON \
    -DOPENAL_INCLUDE_DIR="$RG_SYSROOT/usr/include/AL" -DOPENAL_LIBRARY="$RG_SYSROOT/usr/lib/libopenal.so" \
    -DLIBOPENMPT_INCLUDE_DIR="$RG_SYSROOT/usr/include/libopenmpt" -DLIBOPENMPT_LIBRARY="$RG_SYSROOT/usr/lib/libopenmpt.so" \
    -DWITH_MULTIPLAYER=OFF -DWITH_ONLINE_MULTIPLAYER=OFF -DCMAKE_DISABLE_FIND_PACKAGE_CURL=ON -DNCINE_WITH_BACKWARD=OFF -DNCINE_DOWNLOAD_DEPENDENCIES=OFF \
    -DNCINE_LINKTIME_OPTIMIZATION=OFF -DDEATH_CPU_USE_IFUNC=OFF -DNCINE_VERSION_FROM_GIT=OFF \
    -DCMAKE_C_FLAGS_RELEASE="-O2 -DNDEBUG" -DCMAKE_CXX_FLAGS_RELEASE="-O2 -DNDEBUG" -DCMAKE_EXPORT_COMPILE_COMMANDS=ON 2>&1 | tee "$WORK/logs/configure.log"
cmake --build "$WORK/build" --target jazz2 --parallel "$JOBS" 2>&1 | tee "$WORK/logs/build.log"
